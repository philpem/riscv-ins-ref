"""DOM transformations that turn Arm's generated XHTML into the site's pages.

The source tarballs already contain ``xhtml/*.html`` generated by Arm's own
XSLT.  Re-running the XSLT is possible, but the pre-generated pages are the
canonical input: they preserve the exact markup, whitespace and links that the
published site was built from.  This module only applies the differences
between Arm's pages and the community site.
"""

from __future__ import annotations

import re
from pathlib import Path

from lxml import etree

XHTML = "http://www.w3.org/1999/xhtml"


def q(local: str) -> str:
    return f"{{{XHTML}}}{local}"


def local_name(element: etree._Element) -> str:
    tag = element.tag
    if not isinstance(tag, str):
        return ""
    return tag.rsplit("}", 1)[-1]


def parse_xhtml(path: str | Path) -> etree._ElementTree:
    parser = etree.XMLParser(
        load_dtd=False,
        no_network=True,
        resolve_entities=False,
        huge_tree=True,
        recover=True,
    )
    return etree.parse(str(path), parser)


def body_of(tree: etree._ElementTree) -> etree._Element:
    body = tree.getroot().find(q("body"))
    if body is None:
        body = tree.getroot().find("body")
    if body is None:
        raise ValueError("document has no body element")
    return body


def text_of(element: etree._Element | None) -> str:
    if element is None:
        return ""
    return "".join(element.itertext())


def _remove_element(element: etree._Element) -> None:
    parent = element.getparent()
    if parent is not None:
        parent.remove(element)


def _strip_arm_chrome(body: etree._Element) -> None:
    """Remove Arm's own top/bottom navigation and copyright blocks."""

    for table in list(body.iter(q("table"))):
        if table.find(f".//{q('div')}[@class='topbar']") is not None:
            _remove_element(table)

    # The remaining direct <hr> elements are the separators around Arm's
    # top/bottom navigation.  The site supplies its own footer rule.
    for child in list(body):
        if local_name(child) == "hr":
            body.remove(child)

    for paragraph in list(body.iter(q("p"))):
        if paragraph.get("class") in {"versions", "copyconf"}:
            _remove_element(paragraph)


def _replace_tag(element: etree._Element, name: str) -> etree._Element:
    replacement = etree.Element(q(name), attrib=dict(element.attrib))
    replacement.text = element.text
    replacement.tail = element.tail
    for child in list(element):
        replacement.append(child)
    parent = element.getparent()
    if parent is not None:
        parent.replace(element, replacement)
    return replacement


def _serialize_body(body: etree._Element) -> str:
    # Serialise the whole document so the XHTML default namespace is declared
    # once on <html>; serialising the body's children individually makes lxml
    # repeat xmlns="..." on every top-level element.  Slicing the body also
    # preserves the site's XHTML-style ``<br></br>`` serialisation.
    document = etree.tostring(body.getroottree(), method="html", encoding="unicode")
    start = document.index("<body")
    start = document.index(">", start) + 1
    end = document.rindex("</body>")
    return document[start:end]


def _first_paragraph_text(root: etree._Element, path: str) -> str:
    paragraphs = root.findall(path)
    if not paragraphs:
        return ""
    # Keep trailing whitespace: a few authored paragraphs end with significant
    # spaces that the published site preserves in the meta description.
    return "".join(paragraphs[0].itertext()).lstrip()


def instruction_description(xml_path: str | Path) -> str:
    tree = etree.parse(str(xml_path), etree.XMLParser(load_dtd=False, no_network=True, recover=True))
    return _first_paragraph_text(tree.getroot(), ".//authored/para")


def sysreg_description(xml_path: str | Path) -> str:
    tree = etree.parse(str(xml_path), etree.XMLParser(load_dtd=False, no_network=True, recover=True))
    root = tree.getroot()
    description = _first_paragraph_text(root, ".//reg_purpose/purpose_text/para")
    if not description:
        description = _first_paragraph_text(root, ".//purpose_text/para")
    return description


def _transform_classheadings(body: etree._Element) -> None:
    """Append " class" to the instruction-class headings.

    Arm's generated page has ``<a>Integer</a>``; the published site shows
    ``Integer class``.  These headings stay at h3 level (they are subheadings
    within an instruction page), unlike the section headings which become h2.
    """

    for heading in body.iter(q("h3")):
        if heading.get("class") != "classheading":
            continue
        anchor = heading.find(q("a"))
        if anchor is None:
            continue
        label = (anchor.tail or "").rstrip()
        if label and not label.endswith(" class"):
            anchor.tail = f"{label} class\n        "


def _encoding_labels(xml_path: str | Path) -> dict[str, str]:
    """Map encoding anchor names to Arm's own encoding labels.

    Most encodings have no label.  A few multi-class SME instructions do, and
    Arm's newer page generator folds that label into the heading ("8-bit
    encoding").  The pre-generated XHTML in the Preview bundle still says just
    "Encoding", so recover the label from the XML.
    """

    root = etree.parse(
        str(xml_path), etree.XMLParser(load_dtd=False, no_network=True, recover=True)
    ).getroot()
    labels: dict[str, str] = {}
    for encoding in root.iter("encoding"):
        name = encoding.get("name")
        label = (encoding.get("label") or "").strip()
        if name and label:
            labels[name] = label
    return labels


def _transform_encoding_labels(
    body: etree._Element, labels: dict[str, str] | None = None
) -> None:
    labels = labels or {}
    for encoding in list(body.iter(q("div"))):
        if encoding.get("class") != "encoding":
            continue
        heading = encoding.find(q("h4"))
        if heading is None or heading.get("class") != "encoding":
            continue

        # Collect the heading, its anchor, and the optional condition span.
        # Everything before the asm-code paragraph belongs in the label.
        nodes: list[etree._Element] = []
        node = heading
        while node is not None and local_name(node) != "p":
            nodes.append(node)
            node = node.getnext()

        wrapper = etree.Element(q("div"))
        wrapper.set("class", "encoding__label")
        encoding.insert(0, wrapper)
        for item in nodes:
            wrapper.append(item)

        # Drop the "Applies when" filler that Arm places between the anchor
        # and the condition span.
        for item in nodes:
            if local_name(item) == "a":
                item.tail = None
            elif local_name(item) == "span" and "bitdiff" in (item.get("class") or ""):
                item.tail = None

        raw_label = (heading.text or "").strip()
        anchor = next(
            (item for item in nodes if local_name(item) == "a" and item.get("id")),
            None,
        )
        xml_label = labels.get(anchor.get("id")) if anchor is not None else None
        if raw_label == "Encoding" and xml_label:
            heading.text = f"{xml_label} encoding\n            "
        elif raw_label.startswith("Encoding for the ") and raw_label.endswith(" variant"):
            label = raw_label[len("Encoding for the ") : -len(" variant")].strip()
            heading.text = f"{label} encoding\n            "
        elif raw_label == "Encoding":
            heading.text = "Encoding"
        else:
            heading.text = raw_label

        # Some labels carry a small feature note in a child span, for example
        # "(FEAT_FP16)".  Keep the markup but normalise the trailing layout
        # whitespace to match the site.
        for br in heading.iter(q("br")):
            if br.tail:
                br.tail = br.tail.strip() + "\n            "
        for span in heading.findall(q("span")):
            if span.text:
                span.text = span.text.strip() + "\n            "


def transform_instruction(
    xhtml_path: str | Path,
    xml_path: str | Path,
    *,
    shared_pseudocode: bool = False,
) -> tuple[str, str, str]:
    """Return ``(body_html, title, description)`` for an instruction page."""

    tree = parse_xhtml(xhtml_path)
    body = body_of(tree)
    _strip_arm_chrome(body)

    heading = body.find(q("h2"))
    if heading is None or heading.get("class") != "instruction-section":
        heading = body.find(q("h1"))
    if heading is None:
        raise ValueError(f"no instruction heading in {xhtml_path}")
    title = text_of(heading).strip()

    new_heading = etree.Element(q("h1"))
    new_heading.set("class", "instruction-section")
    new_heading.set("data-pagefind-body", "1")
    new_heading.set("data-pagefind-weight", "10")
    new_heading.set("data-pagefind-sort", "title")
    new_heading.text = heading.text
    new_heading.tail = heading.tail
    for child in list(heading):
        new_heading.append(child)
    body.replace(heading, new_heading)

    if not shared_pseudocode:
        subtitle = new_heading.getnext()
        if subtitle is not None and local_name(subtitle) == "p":
            subtitle.set("class", "insn_subtitle")
            subtitle.set("data-pagefind-body", "1")
        for paragraph in body.iter(q("p")):
            if paragraph.get("class") == "aml":
                label = re.sub(r"\s+", " ", text_of(paragraph)).strip()
                # "For the ... variant:" labels introduce the following
                # paragraphs; they are not themselves part of the searchable
                # instruction description.
                if label.startswith("For the ") and label.endswith(
                    ("variant:", "variants:")
                ):
                    continue
                paragraph.set("data-pagefind-body", "1")
        for image in body.iter(q("img")):
            if not image.get("class"):
                attributes = dict(image.attrib)
                image.attrib.clear()
                image.set("class", "diagram")
                for key, value in attributes.items():
                    image.set(key, value)

    _transform_classheadings(body)

    for h3 in list(body.iter(q("h3"))):
        if h3.get("class") in {"classheading", "aliastable"}:
            continue
        # Alias pages link to another instruction for the operation and
        # operational information; those headings remain h3 on the site.
        if any(
            local_name(ancestor) == "div"
            and ancestor.get("class") == "alias_ps_section"
            for ancestor in h3.iterancestors()
        ):
            continue
        _replace_tag(h3, "h2")

    for h4 in body.iter(q("h4")):
        heading_text = (h4.text or "").strip()
        if heading_text == "Decode for all variants of this encoding":
            h4.text = "Decode (all encodings)"
        elif heading_text == "Decode for this encoding":
            h4.text = "Decode"

    _transform_encoding_labels(body, _encoding_labels(xml_path))

    description = "" if shared_pseudocode else instruction_description(xml_path)
    return _serialize_body(body), title, description


def _format_field_heading(heading: etree._Element) -> None:
    condition = heading.find(f"{q('span')}[@class='condition']")
    if condition is not None:
        condition_text = re.sub(r"\s+", " ", text_of(condition)).strip()
        if condition_text.endswith(":"):
            condition_text = condition_text[:-1].rstrip()
        if condition_text.startswith("When "):
            condition_text = "when " + condition_text[len("When ") :]
        for br in list(condition.iter(q("br"))):
            _remove_element(br)
        for child in list(condition):
            condition.remove(child)
        condition.text = condition_text
        condition.tail = ":\n      "
        prefix = (heading.text or "").rstrip()
        heading.text = (prefix + " ") if prefix else " "
        for child in list(heading):
            if child is not condition:
                heading.remove(child)
        return

    if len(heading):
        last = heading[-1]
        last.tail = (last.tail or "").rstrip() + ":\n      "
    else:
        raw = heading.text or ""
        if raw and not raw.strip():
            # Arm emits a few blank field headings (an empty heading followed
            # by a more specific h5).  The site keeps the blank label and
            # renders it as two spaces before the colon.
            heading.text = "  :\n      "
        else:
            heading.text = raw + ":\n      "


def _transform_access_blocks(body: etree._Element) -> None:
    for block in list(body.iter(q("div"))):
        children = list(block)
        if not children:
            continue
        condition = None
        assembler = None
        for child in children:
            if local_name(child) != "h4":
                continue
            if child.get("class") == "condition":
                condition = child
            elif child.get("class") == "assembler":
                assembler = child
        if assembler is None:
            continue
        table = block.getnext()
        if table is None or local_name(table) != "table" or table.get("class") != "access_instructions":
            continue

        asm_lines = text_of(assembler).strip().splitlines()
        asm = asm_lines[0].strip() if asm_lines else ""
        if len(asm_lines) > 1:
            asm += "\n" + "\n".join(
                "          " + line.strip() for line in asm_lines[1:]
            )
        rows = table.findall(q("tr"))
        headers = [text_of(cell).strip() for cell in rows[0].findall(q("th"))] if rows else []
        values = [text_of(cell).strip() for cell in rows[1].findall(q("td"))] if len(rows) > 1 else []
        if len(headers) != len(values):
            raise ValueError(
                f"access-instruction table has {len(headers)} headers but {len(values)} values"
            )
        details = ", ".join(f"{key} = {value}" for key, value in zip(headers, values))

        new_block = etree.Element(q("div"))
        new_block.set("class", "access_block")
        new_block.tail = None
        if condition is not None:
            condition_text = re.sub(r"\s+", " ", text_of(condition)).strip()
            if not condition_text.endswith(":"):
                condition_text += ":"
            condition_heading = etree.SubElement(new_block, q("h4"))
            condition_heading.set("class", "condition")
            condition_heading.text = condition_text

        encoding = etree.SubElement(new_block, q("div"))
        encoding.set("class", "encoding")
        asm_code = etree.SubElement(encoding, q("p"))
        asm_code.set("class", "asm-code")
        asm_code.text = asm

        details_paragraph = etree.Element(q("p"))
        details_paragraph.set("style", "text-align: right")
        details_paragraph.text = f"\n      ({details})\n      "
        details_paragraph.tail = table.tail

        parent = block.getparent()
        if parent is None:
            raise ValueError("access-instruction block is not attached to a document")
        index = parent.index(block)
        parent.remove(block)
        parent.remove(table)
        parent.insert(index, new_block)
        parent.insert(index + 1, details_paragraph)


def _transform_condition_blocks(body: etree._Element) -> None:
    """Turn condition-only access notes into access blocks.

    Some registers (for example the AMU registers) describe accesses by offset
    rather than by an encoding.  Arm emits a plain ``div`` containing a
    condition heading and an explanatory paragraph; the site gives that div
    the same ``access_block`` styling used for encoding-based accesses.
    """

    # Arm emits empty encoding tables after these offset-based descriptions.
    # The site replaces each with an empty encoding-details paragraph.
    for table in list(body.iter(q("table"))):
        if table.get("class") != "access_instructions":
            continue
        if table.find(f".//{q('th')}") is not None or table.find(f".//{q('td')}") is not None:
            continue
        parent = table.getparent()
        if parent is None:
            continue
        details = etree.Element(q("p"))
        details.set("style", "text-align: right")
        details.text = "\n      ()\n      "
        details.tail = table.tail
        parent.replace(table, details)

    for block in list(body.iter(q("div"))):
        if block.get("class") == "access_block":
            continue
        children = list(block)
        if len(children) != 2:
            continue
        heading, paragraph = children
        if local_name(heading) != "h4" or heading.get("class") != "condition":
            continue
        if local_name(paragraph) != "p":
            continue
        block.set("class", "access_block")
        condition_text = re.sub(r"\s+", " ", text_of(heading)).strip()
        if not condition_text.endswith(":"):
            condition_text += ":"
        heading.text = condition_text
        for child in list(heading):
            heading.remove(child)

    # Offset-only access descriptions have no heading at all.
    for block in list(body.iter(q("div"))):
        if block.get("class"):
            continue
        children = list(block)
        if len(children) != 1 or local_name(children[0]) != "p":
            continue
        if "Accessible at offset " not in text_of(children[0]):
            continue
        parent = block.getparent()
        if parent is None or parent.get("class") != "access_mechanisms":
            continue
        block.set("class", "access_block")


def _sysreg_names(xml_path: str | Path) -> tuple[str, str]:
    """Read the short and long names from a register page's XML."""

    tree = etree.parse(str(xml_path), etree.XMLParser(load_dtd=False, no_network=True, recover=True))
    root = tree.getroot()
    short = root.find(".//reg_short_name")
    long = root.find(".//reg_long_name")
    short_text = re.sub(r"\s+", " ", text_of(short)).strip() if short is not None else ""
    # Arm's XML preserves deliberate leading/trailing spaces in a few long
    # names (for example the AP*KeyHi_EL1 "(bits[127:64]) " suffix), and the
    # published site keeps them in the subtitle.
    long_text = text_of(long) if long is not None else ""
    return short_text, long_text


def transform_sysreg(xhtml_path: str | Path, xml_path: str | Path) -> tuple[str, str, str]:
    """Return ``(body_html, short_name, description)`` for a register page."""

    tree = parse_xhtml(xhtml_path)
    body = body_of(tree)
    _strip_arm_chrome(body)

    heading = body.find(q("h1"))
    if heading is None or heading.get("class") != "register-section":
        raise ValueError(f"no register heading in {xhtml_path}")
    full_name = re.sub(r"\s+", " ", text_of(heading)).strip()
    name_parts = [part.strip() for part in full_name.split(", ")]
    xml_short, xml_long = _sysreg_names(xml_path)

    array_suffix = ""
    if len(name_parts) >= 3 and re.fullmatch(r"[nm] = \d+ - \d+", name_parts[-1]):
        array_suffix = name_parts[-1]

    # Prefer the XML names: Arm's heading flattens short name, long name and
    # array range into one comma-separated string, which is ambiguous for
    # short names that themselves contain commas (system instructions).
    if xml_short:
        title_name = xml_short
        short_name = f"{xml_short}, {array_suffix}" if array_suffix else xml_short
        long_name = xml_long
        has_subtitle = bool(long_name)
    else:
        title_name, separator, long_name = full_name.partition(", ")
        short_name = title_name
        has_subtitle = bool(separator)

    heading.text = short_name
    heading.set("data-pagefind-body", "1")
    heading.set("data-pagefind-weight", "10")
    heading.set("data-pagefind-sort", "title")

    if has_subtitle:
        subtitle = etree.Element(q("p"))
        subtitle.set("class", "insn_subtitle")
        subtitle.set("data-pagefind-body", "1")
        subtitle.text = long_name
        subtitle.tail = heading.tail
        heading.tail = None
        body.insert(body.index(heading) + 1, subtitle)

    for paragraph in list(body.iter(q("p"))):
        text = (paragraph.text or "").strip()
        if text.startswith("The ") and text.endswith(" characteristics are:"):
            _remove_element(paragraph)

    for section in list(body.findall(q("h2"))):
        if text_of(section).strip() != "Purpose":
            continue
        wrapper = etree.Element(q("div"))
        wrapper.set("data-pagefind-body", "1")
        wrapper.text = section.tail
        section.tail = None
        index = body.index(section)
        body.remove(section)
        body.insert(index, wrapper)
        sibling = wrapper.getnext()
        while sibling is not None and local_name(sibling) != "h2":
            following = sibling.getnext()
            wrapper.append(sibling)
            sibling = following
        break

    for section in body.findall(q("h2")):
        if text_of(section).strip() in {"Configuration", "Attributes"}:
            section.tag = q("h3")

    for field_heading in body.iter(q("h4")):
        if (field_heading.get("id") or "").startswith("fieldset_"):
            _format_field_heading(field_heading)

    for span in list(body.iter(q("span"))):
        if span.get("class") == "note-header":
            parent = span.getparent()
            if parent is not None:
                previous = span.getprevious()
                if previous is not None:
                    previous.tail = (previous.tail or "") + (span.tail or "")
                else:
                    parent.text = (parent.text or "") + (span.tail or "")
                parent.remove(span)

    for section in body.iter(q("h2")):
        if not text_of(section).strip().startswith("Accessing "):
            continue
        parent = section.getparent()
        if parent is None or parent.get("class") != "access_mechanisms":
            continue
        section.text = "Access Instructions"
        for child in list(section):
            section.remove(child)

    _transform_condition_blocks(body)
    _transform_access_blocks(body)

    description = sysreg_description(xml_path)
    return _serialize_body(body), title_name, description


def escape_text(value: str) -> str:
    """Escape character data for HTML text nodes."""

    return value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def escape_attribute(value: str) -> str:
    # html.escape(quote=True) also turns apostrophes into &#x27;, which is
    # unnecessary inside a double-quoted attribute and differs from lxml's
    # serialisation (and from the published pages).
    return (
        value.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )
